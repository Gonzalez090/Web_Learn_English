// เลือกข้อความตามภาษาของหน้าเว็บ สำหรับ "หัวข้อ/คำอธิบาย" ที่มาจากไฟล์ข้อมูล
// ข้อมูลเก็บเป็นคู่: field (อังกฤษ) กับ fieldTh (ไทย) เช่น name / nameTh
//
// ⚠️ ใช้กับหัวข้อเท่านั้น (ชื่อ Stage, ชื่อบทเรียน, คำอธิบายเกม)
//    เนื้อหาบทเรียน (ประโยคอังกฤษ, คำแปลไทย, คำอ่านไทย) ห้ามเปลี่ยนตามภาษา UI
// =========================================================
export function localized(obj, field, lang) {
  if (!obj) return ''
  const thaiValue = obj[`${field}Th`]
  if (lang === 'th' && thaiValue) return thaiValue
  return obj[field] ?? thaiValue ?? ''
}
